"""Declared generated views, their sources, and stale-view diagnostics."""
from dataclasses import dataclass
from pathlib import Path
import subprocess
import os
import re
from typing import Callable

MARKER_PREFIX = "<!-- Generated by Astrid Dev view: "


@dataclass(frozen=True)
class View:
    name: str
    sources: tuple[str, ...]
    target: str
    render: Callable[[Path], str]
    region: bool | str = False

    @property
    def marker(self) -> str:
        return f"{MARKER_PREFIX}{self.name}; sources: {', '.join(self.sources)}. Do not edit. -->"


def _vision(root: Path) -> str:
    from export_public_vision import build, render_readme
    page = build(root, "0000000000000000000000000000000000000000")
    return render_readme(root, page)


def _root_readme(root: Path) -> str:
    from export_public_vision import build, render_root_readme
    page = build(root, "0000000000000000000000000000000000000000")
    return render_root_readme((root / "README.md").read_text(encoding="utf-8"), page)


def _checks(root: Path) -> str:
    import sys
    result = subprocess.run([sys.executable, str(root / "scripts/astrid_dev.py"), "list"],
                            cwd=root, check=True, capture_output=True, text=True)
    return "# Registered checks\n\n" + "\n".join(f"- `{line}`" for line in result.stdout.splitlines()) + "\n"


def _catalog(root: Path) -> str:
    from records import projects
    path = root / "plans/index.md"
    text = path.read_text(encoding="utf-8")
    start, end = "<!-- plan-catalog:start -->", "<!-- plan-catalog:end -->"
    if text.count(start) != 1 or text.count(end) != 1:
        raise ValueError("view plan-catalog: plans/index.md must contain exactly one <!-- plan-catalog:start --> line and one <!-- plan-catalog:end --> line around the table; restore them")
    before, rest = text.split(start, 1)
    _, after = rest.split(end, 1)
    lines = ["| Plan | Project | Goal | Status | Owner | Estimate | Waiting on |",
             "|---|---|---|---|---|---:|---|"]
    for row in projects(root):
        folder = re.search(r"\(([^/]+)/plan\.md\)", row[6]).group(1)
        values = [rebase_links(v, Path("plans") / folder, Path("plans")) for v in row[:6]]
        lines.append("| " + " | ".join([row[6], *values]) + " |")
    return before + start + "\n" + "\n".join(lines) + "\n" + end + after


def _status_definitions(root: Path) -> str:
    from lifecycle import definitions
    path = root / "plans/index.md"
    text = path.read_text(encoding="utf-8")
    start, end = "<!-- status-definitions:start -->", "<!-- status-definitions:end -->"
    if text.count(start) != 1 or text.count(end) != 1:
        return text
    before, rest = text.split(start, 1)
    _, after = rest.split(end, 1)
    return before + start + "\n" + definitions() + "\n" + end + after


VIEWS = (
    View("public-vision", ("vision/", "plans/*/plan.md", "plans/priority.md"), "vision/README.md", _vision),
    View("root-vision-summary", ("vision/", "plans/*/plan.md", "plans/priority.md"), "README.md", _root_readme, "vision-summary"),
    View("plan-catalog", ("plans/*/plan.md", "plans/priority.md"), "plans/index.md", _catalog, "plan-catalog"),
    View("status-definitions", ("scripts/lifecycle.py",), "plans/index.md", _status_definitions, "status-definitions"),
    View("check-catalog", ("scripts/checks.py",), "docs/checks.md", _checks),
)


def _with_marker(view: View, content: str) -> str:
    if view.region:
        region = "vision-summary" if view.region is True else view.region
        start = f"<!-- {region}:start -->"
        end = f"<!-- {region}:end -->"
        if content.count(start) != 1 or content.count(end) != 1:
            raise ValueError(f"view {view.name}: target must contain exactly one {start} line and one {end} line; restore them in {view.target}")
        if content.count(view.marker) == 1:
            return content
        before, rest = content.split(start, 1)
        _, after = rest.split(end, 1)
        generated = rest.split(end, 1)[0].lstrip("\n").rstrip("\n")
        generated = "\n".join(line for line in generated.splitlines() if not line.startswith(MARKER_PREFIX))
        return before + start + "\n" + view.marker + "\n" + generated + "\n" + end + after
    if content.startswith(view.marker + "\n"):
        return content
    if content.startswith(MARKER_PREFIX):
        content = content.split("\n", 1)[1]
    return view.marker + "\n" + content


def expected(view: View, root: Path) -> str:
    return _with_marker(view, view.render(root))


def touched(view: View, root: Path, base: str) -> bool:
    """Compare the generated part at the merge base with the working tree."""
    root = root.resolve()
    try:
        merge_base = subprocess.check_output(
            ["git", "merge-base", base, "HEAD"], cwd=root, text=True,
            stderr=subprocess.PIPE).strip()
    except subprocess.CalledProcessError as exc:
        raise ValueError(f"view {view.name}: cannot find merge base for {base}: {exc}") from exc

    def region_content(text: str, revision: str, *, baseline: bool = False) -> str | None:
        if not view.region:
            return text
        region = "vision-summary" if view.region is True else view.region
        start = f"<!-- {region}:start -->"
        end = f"<!-- {region}:end -->"
        if text.count(start) != 1 or text.count(end) != 1:
            if baseline:
                return None
            raise ValueError(f"view {view.name}: {view.target} must contain exactly one {start} and {end} marker pair ({revision})")
        before, remainder = text.split(start, 1)
        content, after = remainder.split(end, 1)
        if after.find(start) >= 0 or before.find(end) >= 0:
            if baseline:
                return None
            raise ValueError(f"view {view.name}: invalid {region} marker order in {view.target} ({revision})")
        return content

    try:
        baseline = subprocess.check_output(
            ["git", "show", f"{merge_base}:{view.target}"], cwd=root,
            stderr=subprocess.PIPE).decode("utf-8")
    except subprocess.CalledProcessError:
        baseline = None
    try:
        current = (root / view.target).read_text(encoding="utf-8")
    except FileNotFoundError:
        current = None
    if baseline is None or current is None:
        if current is not None:
            # Validate a present region even when the target is new.
            region_content(current, "working tree")
        return baseline != current
    baseline_content = region_content(baseline, merge_base, baseline=True)
    current_content = region_content(current, "working tree")
    return baseline_content is None or baseline_content != current_content


def check_view(view: View, root: Path) -> list[str]:
    try:
        actual = (root / view.target).read_text(encoding="utf-8")
        wanted = expected(view, root)
        if actual != wanted:
            return [f"view {view.name}: the generated part of {view.target} does not match its sources; "
                    f"edit {', '.join(view.sources)} instead and undo your change to that part; "
                    f"it refreshes itself on main after merge"]
    except ValueError as exc:
        detail = str(exc).removeprefix(f"view {view.name}: ")
        return [f"view {view.name}: cannot check {view.target}: {detail}; "
                "then run python3 scripts/astrid_dev.py sync"]
    except (OSError, subprocess.CalledProcessError) as exc:
        return [f"view {view.name}: cannot check {view.target}: {exc}; "
                f"{view.target} is generated from {', '.join(view.sources)}, so fix any error there, "
                f"then run python3 scripts/astrid_dev.py sync"]
    return []


def check(root: Path) -> list[str]:
    return [message for view in VIEWS for message in check_view(view, root)]


def sync(root: Path) -> list[str]:
    root = root.resolve()
    targets = []
    for view in VIEWS:
        target_name = Path(view.target)
        if target_name.is_absolute() or ".." in target_name.parts:
            raise ValueError(f"view {view.name}: unsafe target outside repository: {view.target}")
        target = root / target_name
        current = target
        while current != root and current != current.parent:
            if current.is_symlink():
                raise ValueError(f"view {view.name}: target path contains symlink: {view.target}")
            current = current.parent
        if not target.resolve().is_relative_to(root):
            raise ValueError(f"view {view.name}: target outside repository: {view.target}")
        targets.append(target)

    changed = []
    changed_targets = set()
    for view, target in zip(VIEWS, targets):
        content = expected(view, root)
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            target.write_text(content, encoding="utf-8")
            if view.target not in changed_targets:
                changed.append(view.target)
                changed_targets.add(view.target)
    return changed



def rebase_links(value: str, from_dir: Path, to_dir: Path) -> str:
    """Re-base relative Markdown link targets between source directories."""
    def replace(match):
        target = match.group(2)
        if re.match(r"^(?:[a-z][a-z0-9+.-]*:|//|/|#)", target, re.I):
            return match.group(0)
        path, sep, fragment = target.partition("#")
        relative = os.path.relpath(from_dir / path, to_dir)
        return f"[{match.group(1)}]({relative}{sep}{fragment})"
    return re.sub(r"(?<!!)\[([^]\n]+)\]\(([^)\n]+)\)", replace, value)
